// Transform all raw custom cards into prestigious Hall of Fame cards
export const TRANSFORMED_HOF_CARDS: SoccerCard[] = RAW_PROGRAM_ONE_CARDS.map(card => {
  const specific = SPECIFIC_17_TRAITS[card.id];
  let ps = specific?.ps;
  if (!ps) {
    if (card.position === 'GK') ps = PLAYSTYLE_PRESETS.cat_reflexes;
    else if (['CB', 'LB', 'RB'].includes(card.position)) ps = card.stats.def >= 75 ? PLAYSTYLE_PRESETS.anticipate : PLAYSTYLE_PRESETS.bruiser;
    else if (['CM', 'CAM', 'CDM'].includes(card.position)) ps = card.stats.pas >= 72 ? PLAYSTYLE_PRESETS.whipped_pass : PLAYSTYLE_PRESETS.relentless;
    else if (card.stats.pac >= 85) ps = PLAYSTYLE_PRESETS.quick_step;
    else ps = PLAYSTYLE_PRESETS.finesse_shot;
  }

  const inductionYear = specific?.year || 2026;
  const legacyQuote = specific?.quote || `Inducted into the Hall of Fame Class of ${inductionYear} for distinguished match impact.`;

  return {
    ...card,
    rarity: 'hall_of_fame' as const,
    cardStyle: 'hof_gold_obsidian' as const,
    program: 'Hall of Fame',
    playStylePlus: ps,
    hofInductionYear: inductionYear,
    hofLegacyQuote: legacyQuote,
    fullCardImage: generateUserCardSvg(
      card.name,
      card.rating,
      card.position,
      card.stats,
      card.nationFlag,
      card.club,
      card.photoUrl || '⚽',
      'hof_gold_obsidian',
      ps
    ),
  };
});

