// ============================================================================
// CURSED BOARD SNAKES, LADDERS, AND TILE HAZARD DEFINITIONS
// ============================================================================
export interface BoardTile {
  index: number; // 1 to 100
  type: 'start' | 'normal' | 'ladder' | 'snake' | 'card_chest' | 'pack_vault' | 'coins' | 'ouija_nightmare' | 'finish';
  targetIndex?: number; // For snakes (lower) and ladders (higher)
  label?: string;
  lore?: string;
  coinReward?: number;
}

// 8 Bone Ladders (ascending shortcuts)
export const CURSED_LADDERS: { [from: number]: number } = {
  4: 16,
  12: 33,
  24: 48,
  38: 59,
  52: 74,
  63: 81,
  71: 92,
  80: 97,
};

// 8 Cursed Snakes (sliding hazards)
export const CURSED_SNAKES: { [from: number]: number } = {
  28: 10,
  36: 18,
  55: 32,
  68: 45,
  77: 42,
  88: 65,
  94: 70,
  98: 60,
};

// Special Tile Indices
export const CARD_CHEST_TILES = [8, 19, 29, 41, 58, 67, 76, 85, 93];
export const PACK_VAULT_TILES = [15, 34, 62, 89];
export const COIN_TILES = [6, 22, 46, 69, 83];
export const OUIJA_CENTER_TILE = 50; // Exact center of 100-tile board!

export const generateBoardTiles = (): BoardTile[] => {
  const tiles: BoardTile[] = [];
  for (let i = 1; i <= 100; i++) {
    if (i === 1) {
      tiles.push({ index: i, type: 'start', label: 'Cursed Gate', lore: 'Enter the gothic nightmare...' });
    } else if (i === 100) {
      tiles.push({ index: i, type: 'finish', label: 'Valhalla Sanctuary', lore: 'Claim the All-Time Germany Legendary XI!' });
    } else if (i === OUIJA_CENTER_TILE) {
      tiles.push({ index: i, type: 'ouija_nightmare', label: 'OUIJA NIGHTMARE', lore: 'The spirits awaken to drag you down...' });
    } else if (CURSED_LADDERS[i]) {
      tiles.push({ index: i, type: 'ladder', targetIndex: CURSED_LADDERS[i], label: `Bone Ladder (+${CURSED_LADDERS[i] - i})`, lore: 'Spectral bones lift you above the mist.' });
    } else if (CURSED_SNAKES[i]) {
      tiles.push({ index: i, type: 'snake', targetIndex: CURSED_SNAKES[i], label: `Cursed Serpent (-${i - CURSED_SNAKES[i]})`, lore: 'Venomous fangs drag you back into darkness!' });
    } else if (CARD_CHEST_TILES.includes(i)) {
      tiles.push({ index: i, type: 'card_chest', label: 'Germany Card Chest', lore: 'A glowing national relic awaits.' });
    } else if (PACK_VAULT_TILES.includes(i)) {
      tiles.push({ index: i, type: 'pack_vault', label: 'Haunted Pack Vault', lore: 'Uncover an unreleased booster pack.' });
    } else if (COIN_TILES.includes(i)) {
      const amt = 5000 + Math.floor((i / 100) * 20000);
      tiles.push({ index: i, type: 'coins', coinReward: amt, label: `Grave Vault (+${amt.toLocaleString()} 🪙)` });
    } else {
      tiles.push({ index: i, type: 'normal', label: `Tile ${i}` });
    }
  }
  return tiles;
};
